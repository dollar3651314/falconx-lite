/**
 * 指标单元测试（验收 AC2-18：数值和公式一致，用固定数据对照）。
 *
 * 期望值的来源（都不是用被测代码算的）：
 * 1. 手算：小数据直接按定义算（常数序列、1～5 的布林带、全涨全平的 RSI 等）。
 * 2. 独立参考实现：另写了一份 Python 实现（decimal 28 位精度，逐窗口直接按定义求和、开方，不用 JS 里的递推写法），
 *    算出下面 FIX 数据和 StockCharts 示例数据的期望值，原样抄成常量。参考实现的核心如下，复核时可以直接运行：
 *
 *      from decimal import Decimal as D, getcontext; getcontext().prec = 28
 *      def ema(v, n):  # 跳过前面的 None；种子 = 前 n 个的简单平均；a = 2/(n+1)
 *          out=[None]*len(v); s=[i for i,x in enumerate(v) if x is not None][0]; a=D(2)/D(n+1)
 *          p=sum(v[s:s+n])/D(n); out[s+n-1]=p
 *          for i in range(s+n,len(v)): p=a*v[i]+(1-a)*p; out[i]=p
 *          return out
 *      def boll(v,n=20,k=2):  # 总体标准差（除以 n）
 *          w=v[i-n+1:i+1]; m=sum(w)/D(n); sd=(sum((x-m)**2 for x in w)/D(n)).sqrt(); return m, m+k*sd, m-k*sd
 *      def macd(v):  dif=ema(v,12)-ema(v,26); dea=ema(dif,9); hist=2*(dif-dea)
 *      def rsi(v,n=14):  # Wilder：首值 = 前 n 次涨跌的简单平均，之后 (avg*(n-1)+本次)/n；跌幅平均为 0 时 100
 *
 * 3. StockCharts ChartSchool 的 EMA（10 日）和 RSI（14 日）示例数据：这两组价格是技术分析教材里常用的公开样例，
 *    期望值同样由上面的 Python 实现算出（EMA 首值 22.22、RSI 首值 70.46，和常被引用的数值相符；本次没有联网核对原始表格）。
 */
import { describe, expect, it } from 'vitest';
import { boll, ema, INDICATOR_LABEL, macd, rsi, sma, type Series } from './indicators';

/** 和期望数组逐项比较：null 位置必须一致，数值误差小于 10^-digits / 2 */
function expectSeries(got: Series, want: Array<number | null>, digits = 8) {
  expect(got).toHaveLength(want.length);
  want.forEach((w, i) => {
    if (w === null) expect(got[i], `第 ${i} 项应为 null`).toBeNull();
    else expect(got[i], `第 ${i} 项`).toBeCloseTo(w, digits);
  });
}
const nulls = (n: number) => new Array<null>(n).fill(null);

// 固定数据：40 根，确定性的锯齿 + 趋势：100 + 0.5i + (7i mod 11) − 0.8 × (3i mod 5)
const FIX = Array.from({ length: 40 }, (_, i) => 100 + i * 0.5 + ((i * 7) % 11) - ((i * 3) % 5) * 0.8);

describe('手算可核对的小例子', () => {
  it('MA：1～6 的 3 日平均', () => {
    expectSeries(sma([1, 2, 3, 4, 5, 6], 3), [null, null, 2, 3, 4, 5]);
  });
  it('EMA：种子是前 n 个的平均，之后 α = 2/(n+1)', () => {
    // n=3，α=0.5：种子 (1+2+3)/3=2；之后 0.5×4+0.5×2=3；0.5×10+0.5×3=6.5
    expectSeries(ema([1, 2, 3, 4, 10], 3), [null, null, 2, 3, 6.5]);
    expectSeries(ema([5, 5, 5, 5, 5, 5], 4), [null, null, null, 5, 5, 5]);
    expectSeries(ema([1, 2], 3), [null, null]);
  });
  it('BOLL：1～5，中轨 3，总体标准差 √2，上下轨 3 ± 2√2', () => {
    const b = boll([1, 2, 3, 4, 5], 5, 2);
    expectSeries(b.mid, [null, null, null, null, 3]);
    expectSeries(b.upper, [null, null, null, null, 3 + 2 * Math.SQRT2]);
    expectSeries(b.lower, [null, null, null, null, 3 - 2 * Math.SQRT2]);
    const flat = boll(new Array(20).fill(7));
    expect(flat.upper[19]).toBe(7);
    expect(flat.lower[19]).toBe(7);
  });
  it('RSI：一直涨是 100，一直跌是 0，不动是 50；数据不够全是 null', () => {
    const up = Array.from({ length: 20 }, (_, i) => 10 + i);
    expect(rsi(up)[14]).toBe(100);
    expect(rsi(up)[19]).toBe(100);
    expect(rsi(up.slice().reverse())[19]).toBe(0);
    expect(rsi(new Array(20).fill(3))[19]).toBe(50);
    expectSeries(rsi(up.slice(0, 14)), nulls(14));
    // n=2：涨跌 +2、−1 → 平均涨 1、跌 0.5，RS=2，RSI=66.666…；下一次 +3 → 涨 (1+3)/2=2、跌 0.25，RS=8，RSI=88.888…
    expectSeries(rsi([10, 12, 11, 14], 2), [null, null, 200 / 3, 800 / 9]);
  });
  it('MACD：常数序列 DIF、DEA、柱都是 0；DIF 从第 26 根开始，DEA 和柱从第 34 根开始', () => {
    const m = macd(new Array(40).fill(100));
    expect(m.dif[24]).toBeNull();
    expect(m.dif[25]).toBe(0);
    expect(m.dea[32]).toBeNull();
    expect(m.dea[33]).toBe(0);
    expect(m.hist[33]).toBe(0);
  });
});

